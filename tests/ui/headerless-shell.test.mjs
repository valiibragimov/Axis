import test from 'node:test';
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { resolve } from 'node:path';
import { startStaticServer } from '../smoke/helpers/static-server.mjs';

test('headerless shell lifts navigation and keeps a keyboard-accessible mobile drawer', async () => {
  const server = await startStaticServer(resolve('dist-demo'));
  const browser = await chromium.launch({ headless: true, ...(process.platform === 'win32' ? {channel:'chrome'} : {}) });
  try {
    const page = await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
    const errors=[]; page.on('pageerror', e=>errors.push(e.message));
    await page.goto(server.url+'/demo.html');
    await page.locator('#overviewReadinessValue').filter({hasText:'0%'}).waitFor();
    assert.equal(await page.locator('body > header').count(),0);
    const nav=page.locator('#workspaceSidebar'), toggle=page.locator('#sidebarToggle');
    const bounds=await nav.boundingBox();
    assert.equal(bounds.y,0); assert.equal(bounds.height,1000);
    assert.ok((await toggle.boundingBox()).y<24);
    assert.ok((await page.locator('.sidebar-brand').boundingBox()).y<32);
    assert.ok((await nav.locator('[data-target="overview"]').boundingBox()).y<80);
    assert.equal((await page.locator('main').boundingBox()).y,0);
    const handle=page.locator('.sidebar-resize');
    await handle.press('Home');
    assert.equal(Math.round((await nav.boundingBox()).width),64);
    assert.equal(await page.locator('.sidebar-brand').isVisible(),false);
    await page.setViewportSize({width:390,height:844});
    assert.equal(await toggle.getAttribute('aria-expanded'),'false');
    assert.equal(await page.locator('.sidebar-scroll').evaluate(el=>el.inert),true);
    await toggle.focus(); await toggle.press('Enter');
    assert.equal(await toggle.evaluate(el=>document.activeElement===el),true);
    await page.keyboard.press('Tab');
    assert.equal(await nav.locator('[data-target="overview"]').evaluate(el=>document.activeElement===el),true);
    assert.equal(await toggle.getAttribute('aria-expanded'),'true');
    assert.equal((await nav.boundingBox()).x,0);
    assert.equal(await page.locator('.sidebar-brand').isVisible(),true);
    assert.equal(await page.locator('.sidebar-scroll').evaluate(el=>el.inert),false);
    await nav.locator('[data-target="geo"]').click();
    await page.locator('#geo.active').waitFor();
    assert.equal(await toggle.getAttribute('aria-expanded'),'false');
    await toggle.click(); await page.keyboard.press('Escape');
    assert.equal(await toggle.getAttribute('aria-expanded'),'false');
    assert.equal(await toggle.evaluate(el=>document.activeElement===el),true);
    await toggle.click(); await page.locator('.sidebar-backdrop').click({position:{x:385,y:300}});
    assert.equal(await toggle.getAttribute('aria-expanded'),'false');
    assert.equal(await page.locator('#bottomNav').isVisible(),true);
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    await page.setViewportSize({width:1440,height:1000});
    assert.equal(Math.round((await nav.boundingBox()).width),64);
    await handle.press('End'); assert.equal(Math.round((await nav.boundingBox()).width),360);
    assert.deepEqual(errors,[]);
  } finally {await browser.close();await server.close();}
});
